import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  anim,
  EYE_MASKS,
  eyesAt,
  frameAt,
  frameCount,
  keyframesCss,
  MASCOT_STATES,
  mascotState,
  nextBlinkDelay,
  offsetAt,
  PAD,
  PART_NAMES,
  SLEEP_AFTER_MS,
  sprite,
  trackOf,
  TRACKS,
  viewBox,
  zzzCells,
  type MascotInputs,
} from './unicrab';

describe('unicrab.sprite.json (generated by scripts/sprite-from-png.py)', () => {
  it('has the expected shape: grid, palette, every part, every eye mask', () => {
    expect(sprite.width).toBeGreaterThanOrEqual(18);
    expect(sprite.width).toBeLessThanOrEqual(30);
    expect(sprite.height).toBeGreaterThanOrEqual(16);
    expect(sprite.palette.length).toBeGreaterThan(4);
    for (const c of sprite.palette) expect(c).toMatch(/^#[0-9a-f]{6}$/);
    expect(Object.keys(sprite.parts).sort()).toEqual([...PART_NAMES].sort());
    expect(Object.keys(sprite.eyes).sort()).toEqual([...EYE_MASKS].sort());
    for (const name of PART_NAMES) expect(sprite.parts[name].length, name).toBeGreaterThan(0);
  });

  it('cells are in the grid, use palette colours and never overlap across parts', () => {
    const seen = new Map<string, string>();
    for (const name of PART_NAMES) {
      if (name === 'eye-left' || name === 'eye-right') continue; // drawn over the (solid) visor
      for (const [x, y, c] of sprite.parts[name]) {
        expect(x).toBeGreaterThanOrEqual(0);
        expect(x).toBeLessThan(sprite.width);
        expect(y).toBeGreaterThanOrEqual(0);
        expect(y).toBeLessThan(sprite.height);
        expect(c).toBeLessThan(sprite.palette.length);
        const key = `${x},${y}`;
        expect(seen.get(key), `${key} in ${name} and ${seen.get(key)}`).toBeUndefined();
        seen.set(key, name);
      }
    }
  });

  it('labels parts where a crab has them: claws up top, legs low, eyes inside the visor, left/right mirrored', () => {
    const cx = (cells: number[][]) => cells.reduce((s, c) => s + c[0]!, 0) / cells.length;
    const cy = (cells: number[][]) => cells.reduce((s, c) => s + c[1]!, 0) / cells.length;
    const p = sprite.parts;
    expect(cy(p['claw-left'])).toBeLessThan(cy(p.visor));
    expect(cy(p['legs-left'])).toBeGreaterThan(cy(p.visor));
    expect(cx(p['claw-left'])).toBeLessThan(sprite.width / 2);
    expect(cx(p['claw-right'])).toBeGreaterThan(sprite.width / 2);
    expect(cx(p['eye-left'])).toBeLessThan(cx(p['eye-right']));
    const vx = p.visor.map((c) => c[0]!);
    const vy = p.visor.map((c) => c[1]!);
    for (const [x, y] of [...p['eye-left'], ...p['eye-right']]) {
      expect(x).toBeGreaterThanOrEqual(Math.min(...vx));
      expect(x).toBeLessThanOrEqual(Math.max(...vx));
      expect(y).toBeGreaterThanOrEqual(Math.min(...vy));
      expect(y).toBeLessThanOrEqual(Math.max(...vy));
    }
    // The outline is the darkest colour and every part carries some of it (it moves with the part).
    for (const name of ['claw-left', 'claw-right', 'legs-left', 'legs-right', 'body'] as const)
      expect(p[name].some((c) => c[2] === sprite.roles.outline), name).toBe(true);
  });

  it('blink and closed eyes are one row; happy eyes are a ^ (two rows)', () => {
    const rows = (mask: (typeof EYE_MASKS)[number]) => new Set(sprite.eyes[mask].map((c) => c[1])).size;
    expect(rows('blink')).toBe(1);
    expect(rows('closed')).toBe(1);
    expect(rows('happy')).toBe(2);
    expect(rows('open')).toBeGreaterThan(1);
  });

  it('the committed JSON is what the script would write for the committed PNG (no hand edits)', () => {
    const raw = readFileSync(resolve(__dirname, '../assets/unicrab/unicrab.sprite.json'), 'utf8');
    expect(raw.endsWith('\n')).toBe(true);
    expect(JSON.parse(raw).source.png).toBe('unicrab-pixel.png');
  });
});

describe('unicrab.anim.json', () => {
  it('has every state, with whole-cell offsets that stay inside the padding', () => {
    expect(Object.keys(anim.states).sort()).toEqual([...MASCOT_STATES].sort());
    for (const state of MASCOT_STATES) {
      const s = anim.states[state];
      expect(s.frameMs).toBeGreaterThanOrEqual(80);
      expect(s.opacity).toBeGreaterThan(0);
      expect(s.opacity).toBeLessThanOrEqual(1);
      for (const mask of s.eyes) expect(EYE_MASKS).toContain(mask);
      for (const [track, frames] of Object.entries(s.tracks)) {
        expect(TRACKS).toContain(track);
        for (const [dx, dy] of frames!) {
          expect(Number.isInteger(dx) && Number.isInteger(dy)).toBe(true);
          expect(dx).toBeGreaterThanOrEqual(-PAD.left);
          expect(dx).toBeLessThanOrEqual(PAD.right);
          expect(dy).toBeGreaterThanOrEqual(-PAD.top);
          expect(dy).toBeLessThanOrEqual(PAD.bottom);
        }
      }
    }
  });

  it('each state does what it says', () => {
    const s = anim.states;
    // working: claws clack alternately, eyes scan left and right
    const l = s.working.tracks['claw-left']!;
    const r = s.working.tracks['claw-right']!;
    expect(l.some((o, i) => (o[0] || o[1]) && !(r[i]![0] || r[i]![1]))).toBe(true);
    expect(s.working.eyes).toContain('left');
    expect(s.working.eyes).toContain('right');
    // needs-you: hops (the whole crab goes up) and both claws wave
    expect(Math.min(...s['needs-you'].tracks.all!.map((o) => o[1]))).toBeLessThan(0);
    expect(s['needs-you'].tracks['claw-left']!.some((o) => o[0] < 0)).toBe(true);
    expect(s['needs-you'].tracks['claw-right']!.some((o) => o[0] > 0)).toBe(true);
    // done: happy eyes + bounce
    expect(s.done.eyes).toEqual(['happy']);
    expect(Math.min(...s.done.tracks.all!.map((o) => o[1]))).toBeLessThan(0);
    // offline: dim, eyes closed, still; sleep: eyes closed, Z's
    expect(s.offline.opacity).toBeLessThan(0.6);
    expect(s.offline.eyes).toEqual(['closed']);
    expect(Object.keys(s.offline.tracks)).toEqual([]);
    expect(s.sleep.eyes).toEqual(['closed']);
    expect(s.sleep.tracks.zzz).toBeTruthy();
    // idle: a 1-cell breathe, random blink
    expect(s.idle.blink).toBe(true);
    expect(Math.max(...s.idle.tracks.torso!.map((o) => Math.abs(o[1])))).toBe(1);
  });
});

describe('rig helpers', () => {
  const working = anim.states.working;
  it('frameAt/offsetAt/eyesAt step through the loop', () => {
    const n = frameCount(working);
    expect(n).toBe(8);
    expect(frameAt(working, 0)).toBe(0);
    expect(frameAt(working, working.frameMs * 3 + 1)).toBe(3);
    expect(frameAt(working, working.frameMs * n)).toBe(0);
    expect(frameAt(working, -50)).toBe(0);
    expect(offsetAt(working, 'claw-left', 1)).toEqual([1, 1]);
    expect(offsetAt(working, 'all', 3)).toEqual([0, 0]);
    expect(eyesAt(working, 1)).toBe('left');
    expect(eyesAt(working, 5)).toBe('right');
    // working never blinks; idle does when the timer says so
    expect(eyesAt(working, 0, true)).toBe('open');
    expect(eyesAt(anim.states.idle, 0, true)).toBe('blink');
  });

  it('trackOf: torso parts share a track, the rest have their own', () => {
    expect(trackOf('visor')).toBe('torso');
    expect(trackOf('eye-left')).toBe('torso');
    expect(trackOf('claw-right')).toBe('claw-right');
  });

  it('nextBlinkDelay stays inside blinkEvery', () => {
    expect(nextBlinkDelay(() => 0)).toBe(anim.blinkEvery[0]);
    expect(nextBlinkDelay(() => 0.999999)).toBeLessThanOrEqual(anim.blinkEvery[1]);
  });

  it('viewBox pads the sprite for hops and Z\'s; Z cells sit in the padding', () => {
    expect(viewBox()).toBe(`${-PAD.left} ${-PAD.top} ${sprite.width + PAD.left + PAD.right} ${sprite.height + PAD.top + PAD.bottom}`);
    for (const [x, y] of zzzCells()) {
      expect(x).toBeLessThan(sprite.width + PAD.right);
      expect(y).toBeGreaterThanOrEqual(-PAD.top);
    }
  });

  it('keyframesCss: steps(), whole-cell translations, reduced-motion stop', () => {
    const css = keyframesCss();
    expect(css).toContain('steps(1,end)');
    expect(css).toMatch(/@keyframes uc-working-claw-left\{0%\{transform:translate\(0px,0px\)\}12\.5%\{transform:translate\(1px,1px\)\}/);
    expect(css).not.toMatch(/translate\(-?\d+\.\d/); // never a fractional cell
    expect(css).toContain('prefers-reduced-motion: reduce');
    expect(css).toContain('.unicrab[data-state="offline"]{opacity:0.45}');
    // idle has no motion for `all` (only torso + claws breathe)
    expect(css).not.toContain('uc-idle-all');
    // blink override only for states that blink
    expect(css).toContain('.unicrab[data-state="idle"][data-blink] [data-eyes="blink"]{visibility:visible}');
    expect(css).not.toContain('.unicrab[data-state="working"][data-blink]');
  });
});

describe('mascotState', () => {
  const base: MascotInputs = { hosts: 1, offlineHosts: 0, waiting: 0, finished: 0, running: 0, quietMs: 0 };
  it('picks by priority: needs-you > done > working > offline > sleep > idle', () => {
    expect(mascotState(base)).toBe('idle');
    expect(mascotState({ ...base, quietMs: SLEEP_AFTER_MS })).toBe('sleep');
    expect(mascotState({ ...base, offlineHosts: 1, quietMs: SLEEP_AFTER_MS })).toBe('offline');
    expect(mascotState({ ...base, offlineHosts: 1, running: 1 })).toBe('working');
    expect(mascotState({ ...base, running: 2, finished: 1 })).toBe('done');
    expect(mascotState({ ...base, running: 2, finished: 1, waiting: 1 })).toBe('needs-you');
  });
  it('no hosts is not "offline"; one of two hosts down is not either', () => {
    expect(mascotState({ ...base, hosts: 0 })).toBe('idle');
    expect(mascotState({ ...base, hosts: 2, offlineHosts: 1 })).toBe('idle');
  });
});
