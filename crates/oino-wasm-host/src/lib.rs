//! `oino-wasm-host`: the wasmtime component host for `oino:extension@1.0.0` (extension-api §5).
//!
//! # Boundary
//!
//! Implements [`oino_extension_api::ExtensionRuntime`]. Host imports that touch sessions, UI,
//! models or agents delegate to [`oino_extension_api::HostServices`]; `process`, `http`, `fs`,
//! `timers`, `kv`, `log`, `host-info` and `provider-host` are served here, each import checking
//! the manifest grant first (§5.3). [`LocalServices`] serves bus, services, secrets and tasks
//! until core takes them over. With feature `core`, [`core_bridge`] plugs the runtime into
//! `oino-core`'s extension runner.
//!
//! # Unsafe
//!
//! The crate denies `unsafe_code`; the only exception is the `bindings` module generated by
//! `wasmtime::component::bindgen!`, whose typed export accessors use `TypedFunc::new_unchecked`
//! (the types are checked against the component at instantiation).
//!
//! # API map
//!
//! | Item | Contents |
//! |---|---|
//! | [`WasmRuntime`], [`WasmRuntimeOptions`] | engine (async component model, epoch ticks, compile cache), linker, loading |
//! | [`WasmInstance`] | one instance per extension; actor-driven concurrent calls, trap restart |
//! | [`HostConfig`] | agent dir, cwd, proxy, versions |
//! | [`LocalServices`] | bus, services, secrets, background tasks, host event delivery |
//! | [`packages`] | package discovery (`extension.json` + component) |
//! | [`core_bridge`] (feature `core`) | adapters to `oino_core::extensions` and `services::ExtensionLoader` |
//! | `testing` (feature) | fixture builder + harness |

