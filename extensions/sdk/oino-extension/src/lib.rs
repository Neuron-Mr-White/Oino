//! Guest SDK for Oino WASM component extensions (`oino:extension@1.0.0`).
//!
//! An extension is a type implementing [`Extension`]; [`export_extension!`] turns it into a
//! component. `init` registers events, tools, commands, shortcuts, flags, services, settings,
//! renderers and arbiter roles through [`Init`]; handlers are plain async closures or methods
//! receiving `&'static Self`. Host capabilities are thin typed wrappers over the WIT imports:
//!
//! | Module | WIT | Use |
//! |---|---|---|
//! | [`session`] | `session` | entries, `append_entry`, `send_message`, sessions index |
//! | [`control`] | `control` | model, thinking, tools, commands, compaction, command-context ops |
//! | [`models`] | `models` | completions, streaming, summaries, credentials |
//! | [`ui`] | `ui` | dialogs, notify/status/widgets, panels, editor, OS integration |
//! | [`agents`] | `agents` | nested agent sessions (subagents) |
//! | [`process`] | `process` | `exec`, spawn with streaming stdio, signals, process trees |
//! | [`tasks`] | `tasks` | host background tasks |
//! | [`http`] | `http` | fetch (streaming), loopback listener |
//! | [`fs`] | `fs` + WASI | named preopens, atomic writes, locks, watchers |
//! | [`timers`] | `timers` | `oino_timer` events, `sleep`, wall clock |
//! | [`kv`] | `kv` | scoped key-value state |
//! | [`settings`] | `registry` | extension settings reads and writes |
//! | [`secrets`], [`bus`], [`services`] | same | secrets, pub/sub, inter-extension calls |
//! | [`browser`] | `browser` | in-app browser commands and status |
//! | [`cron`] | `cron` | scheduled-run scheduler control |
//! | [`host`] | `host-info`, `log` | platform, workspace, env, logging |
//! | [`provider`] (feature `provider`) | `provider`, `provider-host` | provider components |
//!
//! ```ignore
//! use oino_extension::prelude::*;
//!
//! #[derive(Default)]
//! struct Hello;
//!
//! #[derive(Deserialize, JsonSchema)]
//! struct Args { name: String }
//!
//! impl Extension for Hello {
//!     async fn init(&'static self, cx: &mut Init<Self>) -> Result<()> {
//!         cx.tool(Tool::new("hello").description("Greets").args::<Args>()
//!             .run(|_ext, args: Args, _cx| async move { Ok(ToolResult::text(format!("Hello {}", args.name))) }));
//!         cx.on(EventKind::AgentEnd, |_ext, _ev, cx| async move {
//!             session::append_entry("hello.seen", Some(&json!({"session": cx.session_id()})))?;
//!             Ok(())
//!         });
//!         Ok(())
//!     }
//! }
//!
//! oino_extension::export_extension!(Hello);
//! ```

//!
//! # Errors
//!
