/// Exports an [`Extension`] type as the component's guest implementation.
///
/// ```ignore
/// oino_extension::export_extension!(MyExtension);
/// ```
#[macro_export]
macro_rules! export_extension {
    ($ty:ty) => {
        #[doc(hidden)]
        type __OinoExtensionShim = $crate::rt::Shim<$ty>;
        $crate::bindings::export_guest!(__OinoExtensionShim with_types_in $crate::bindings);
    };
}
